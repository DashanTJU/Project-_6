

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


def make_synthetic_plant(capacity_mw: float, days: int, seed: int, start: str = "2024-01-01") -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    times = pd.date_range(start, periods=days * 24, freq=pd.Timedelta(hours=1))
    hour = times.hour.to_numpy()
    doy = times.dayofyear.to_numpy()
    clear_sky = np.clip(np.sin(np.pi * (hour - 6) / 12), 0, None) * (850 + 200 * np.sin(2 * np.pi * (doy - 80) / 365))
    cloudiness = np.repeat(np.clip(rng.normal(0.78, 0.18, days), 0.15, 1.0), 24)
    irradiance = clear_sky * cloudiness * np.clip(rng.normal(1.0, 0.05, times.size), 0.7, 1.2)
    power = capacity_mw * irradiance / 1000.0 * 0.9 + rng.normal(0, 0.01 * capacity_mw, times.size) * (irradiance > 0)
    power = np.clip(power, 0, None)
    temperature = 22 + 10 * np.sin(2 * np.pi * (doy - 110) / 365) + 7 * np.clip(np.sin(np.pi * (hour - 8) / 12), 0, None)
    night = irradiance == 0
    irradiance = np.where(night & (rng.random(times.size) < 0.05), -rng.uniform(0.5, 3.0, times.size), irradiance)
    power = np.where(night & (rng.random(times.size) < 0.03), -0.002 * capacity_mw, power)
    frame = pd.DataFrame({"timestamp": times.strftime("%Y-%m-%d %H:%M:%S"), "power": power.round(4),
                          "irradiance": irradiance.round(3), "temperature": temperature.round(2)})
    frame.loc[200, "temperature"] = -9999.0  
    frame = frame.drop(index=range(3000, 3030))  
    frame = frame.drop(index=[4000])  
    frame = pd.concat([frame, frame.iloc[[500]]], ignore_index=True)  
    return frame


def write_synthetic_inputs(folder: Path, days: int = 400) -> dict[str, Path]:
    """Two synthetic plants: one CSV and one Excel file with a named sheet."""
    folder.mkdir(parents=True, exist_ok=True)
    csv_path = folder / "synthetic_plant_50mw.csv"
    xlsx_path = folder / "synthetic_plant_100mw.xlsx"
    make_synthetic_plant(50.0, days, seed=1).to_csv(csv_path, index=False)
    make_synthetic_plant(100.0, days, seed=2).to_excel(xlsx_path, sheet_name="hourly", index=False)
    (folder / "README_SYNTHETIC.txt").write_text(
        "These files are synthetic test data generated by synthetic_data.py for the smoke test.\n"
        "They are not plant observations and must not be used as research results.\n", encoding="utf-8")
    return {"plant_50mw": csv_path, "plant_100mw": xlsx_path}
